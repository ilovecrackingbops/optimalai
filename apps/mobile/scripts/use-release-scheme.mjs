#!/usr/bin/env node
/**
 * Make Cmd-R build Release.
 *
 * WHY THIS EXISTS: Debug builds load JavaScript from a Metro dev server. That is
 * the right default for someone editing files — it gives hot reload — and the
 * wrong default for someone trying to USE the app. In Debug the phone needs a
 * reachable dev server, dies with "No script URL provided" when it is not, keeps
 * Fast Refresh's habit of corrupting itself after a render error, and runs
 * unoptimized JS several times slower than what ships.
 *
 * Release embeds the JS bundle inside the .app. No server, no LAN, no URL.
 *
 * `ios/` is regenerated by `expo prebuild`, so the scheme edit does not survive
 * on its own. This script re-applies it and runs automatically after prebuild.
 * Switch back any time via Product > Scheme > Edit Scheme > Run.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const IOS_DIR = join(HERE, '../ios')

/**
 * The Xcode project name tracks `name` in app.config.ts (Expo prebuild derives
 * it from the display name, not from BUNDLE_ID/SLUG/SCHEME, which is what
 * app.config.ts's own comment says stays fixed across a rename). Hardcoding
 * "NutAI" here silently broke the day the app became "Optimal AI" — prebuild
 * now regenerates `ios/OptimalAI.xcodeproj`, not `ios/NutAI.xcodeproj`, and
 * this script had quietly done nothing since, with a success-shaped "no iOS
 * project yet" message masking the real problem. Deriving the name from
 * whatever `.xcodeproj` prebuild actually created survives the next rename
 * too.
 */
async function findXcodeProjectName() {
  let entries
  try {
    entries = await readdir(IOS_DIR)
  } catch {
    return null
  }
  const project = entries.find((e) => e.endsWith('.xcodeproj'))
  return project ? project.replace(/\.xcodeproj$/, '') : null
}

async function main() {
  const name = await findXcodeProjectName()
  if (!name) {
    console.log('use-release-scheme: no iOS project yet — run `expo prebuild` first.')
    return
  }
  const SCHEME = join(IOS_DIR, `${name}.xcodeproj/xcshareddata/xcschemes/${name}.xcscheme`)

  let xml
  try {
    xml = await readFile(SCHEME, 'utf8')
  } catch {
    console.log(`use-release-scheme: found ${name}.xcodeproj but no matching scheme file — run \`expo prebuild\` first.`)
    return
  }

  // Only the LaunchAction. TestAction stays on Debug, because tests want
  // assertions and readable stack traces, not an optimized bundle.
  const next = xml.replace(
    /(<LaunchAction\b[\s\S]*?buildConfiguration = ")Debug(")/,
    '$1Release$2',
  )

  if (next === xml) {
    console.log('use-release-scheme: already Release.')
    return
  }

  await writeFile(SCHEME, next, 'utf8')
  console.log('use-release-scheme: Cmd-R now builds Release (no dev server needed).')
}

main().catch((err) => {
  console.error('use-release-scheme failed:', err.message)
  process.exitCode = 1
})
